//! What the Task 7 benchmark leaves out.
//!
//! `benchmark_large_doc.rs` times `CompileSession::recompile` — the Rust
//! recompile alone. The path a user actually feels also marshals the whole
//! document text *into* the command and the compile result back out, on every
//! debounced keystroke. On a 500-page document that's about a megabyte of text
//! per compile, and none of it was measured.
//!
//! This puts a number on that marshalling so the headline guarantee is
//! quantified at the boundary that produces the experience, rather than one
//! layer below it. It asserts a deliberately loose ceiling: the point is to
//! catch marshalling becoming the dominant cost, not to pin an exact number
//! that will flap on a shared CI runner.

use std::time::{Duration, Instant};

const PAGES: usize = 500;
/// Generous on purpose — this guards against a regression that makes
/// marshalling comparable to the 100ms compile budget, not against noise.
const MARSHALLING_BUDGET: Duration = Duration::from_millis(50);

/// Prose written out literally, not generated by `#lorem()`.
///
/// This matters and it caught a bad assumption: the Task 7 fixture builds 500
/// pages from `#lorem(120)` calls, so its *source* is only ~18 KB even though
/// it lays out 500 pages. That's the right fixture for compile cost and the
/// wrong one for marshalling cost, because a document a person actually typed
/// has every one of those words in the file.
fn large_doc() -> String {
    const WORDS_PER_PAGE: usize = 260;
    let vocabulary = [
        "the", "typesetting", "of", "a", "document", "requires", "attention", "to", "detail",
        "and", "patience", "with", "margins", "leading", "kerning", "orphans", "widows",
        "because", "readers", "notice", "what", "they", "cannot", "name",
    ];

    let mut source = String::new();
    let mut word = 0;
    for page in 0..PAGES {
        source.push_str(&format!("= Section {page}\n\n"));
        for _ in 0..WORDS_PER_PAGE {
            source.push_str(vocabulary[word % vocabulary.len()]);
            source.push(' ');
            word += 1;
        }
        source.push('\n');
        if page + 1 < PAGES {
            source.push_str("\n#pagebreak()\n\n");
        }
    }
    source
}

/// The Task 7 budget, re-checked against a document whose *source* is large.
///
/// Task 7's fixture reaches 500 pages through `#lorem()` calls, so it barely
/// exercises parsing. A book someone actually typed is ~866 KB of text, and
/// incremental reparse cost scales with source size — so the 100ms promise
/// deserves to be tested against the realistic shape too, not just the one
/// that happens to compile fast.
#[test]
fn recompiling_a_realistically_large_source_stays_within_budget() {
    use ams_lib::compile::CompileSession;

    let text = large_doc();
    let mut session = CompileSession::detached(text.clone());
    session.recompile(&text).expect("cold compile of a book-sized document");

    let edited = text.replacen("= Section 0", "= Section 0 (edited)", 1);

    let start = Instant::now();
    session.recompile(&edited).expect("recompile after a small edit");
    let elapsed = start.elapsed();

    eprintln!(
        "recompile of {} KB of real source after a small edit: {elapsed:?}",
        text.len() / 1024
    );
    assert!(
        elapsed < Duration::from_millis(100),
        "recompiling {} KB of source took {elapsed:?}, over the 100ms budget",
        text.len() / 1024
    );
}

#[test]
fn marshalling_a_large_document_stays_well_under_the_compile_budget() {
    let text = large_doc();

    // What Tauri does to the `text` argument on the way in: JSON-encode it in
    // the webview, decode it in Rust.
    let start = Instant::now();
    let encoded = serde_json::to_string(&text).expect("text serializes");
    let decoded: String = serde_json::from_str(&encoded).expect("text deserializes");
    let elapsed = start.elapsed();

    assert_eq!(decoded.len(), text.len());
    eprintln!(
        "marshalling {} KB of source (encode + decode): {elapsed:?}",
        text.len() / 1024
    );
    assert!(
        elapsed < MARSHALLING_BUDGET,
        "IPC marshalling of a {PAGES}-page document took {elapsed:?}, budget is {MARSHALLING_BUDGET:?} \
         — at this size it is competing with the compile itself, so the loop should send edits \
         rather than the whole document"
    );
}
